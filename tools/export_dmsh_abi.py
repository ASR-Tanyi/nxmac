#!/usr/bin/env python3
"""The shader library ABI, from nxnative's dm/gfx/nvn/dmsh_abi.h to the header nxmac's shader build compiles (src/dmsh/abi.h).

nxnative keeps the driver segment layout and the binding kinds its host and its shader build share in one C header, which its build reads through
dm/gfx/tools/dmsh_abi.py. This script reads the header as that reader does (the same strict form) and writes each DMSH_<NAME> as a constant k<Name>
of nxmac::dmsh::abi, with the chain version of dm/gfx/nvn/dmsh_chain.h.

    tools/export_dmsh_abi.py                         nxnative beside nxmac -> src/dmsh/abi.h
    tools/export_dmsh_abi.py --nxnative <dir> -o <file>

Run it again when nxnative's dmsh_abi.h or its chain changes, then port what changed in the chain's tools: the constants only name what the
ported code must do. It needs Python 3.12 and nxnative's sources, and formats the header with clang-format (--clang-format, default the one
on PATH; CI's is 23.1.4) as the repository's format-check wants it."""
import argparse, os, re, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFINE = re.compile(r'#define DMSH_([A-Z][A-Z0-9_]*)[ \t]+(0x[0-9A-Fa-f]+|[1-9][0-9]*|0|"[^"\\]*")(?:[ \t]+//[ \t]*(.*))?')


def camel(name):
    return 'k' + ''.join(p[:1] + p[1:].lower() for p in name.split('_'))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--nxnative', default=os.path.join(HERE, '..', '..', 'nxnative'), help='nxnative\'s checkout (default: beside nxmac)')
    ap.add_argument('-o', '--output', default=os.path.normpath(os.path.join(HERE, '..', 'src', 'dmsh', 'abi.h')), help='the header to write')
    ap.add_argument('--clang-format', default=shutil.which('clang-format'), help='clang-format to format the header with (default: on PATH)')
    args = ap.parse_args()
    nvn = os.path.join(os.path.abspath(args.nxnative), 'dm', 'gfx', 'nvn')
    try: text, chain = open(os.path.join(nvn, 'dmsh_abi.h')).read(), open(os.path.join(nvn, 'dmsh_chain.h')).read()
    except OSError as e: sys.exit(f'export_dmsh_abi: {e}')
    m = re.search(r'#define DMSH_CHAIN "([0-9a-f]{12})"', chain)
    if not m: sys.exit('export_dmsh_abi: dmsh_chain.h names no chain version')
    try: commit = subprocess.run(['git', '-C', args.nxnative, 'rev-parse', 'HEAD'], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError): commit = 'unknown commit'
    rows, seen = [], set()
    for n, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        if not s or s.startswith('//') or s == '#pragma once': continue
        d = DEFINE.fullmatch(s)
        if not d: sys.exit(f'export_dmsh_abi: dmsh_abi.h:{n}: not a line dmsh_abi.py can read: {s}')
        name, value, note = d.groups()
        if name in seen: sys.exit(f'export_dmsh_abi: dmsh_abi.h:{n}: DMSH_{name} is defined twice')
        seen.add(name)
        kind = 'std::string_view' if value.startswith('"') else 'int'
        rows.append(f'inline constexpr {kind} {camel(name)} = {value};' + (f'  // {note}' if note and len(note) < 60 else ''))
    out = ['// Generated by tools/export_dmsh_abi.py from nxnative\'s dm/gfx/nvn/dmsh_abi.h and dmsh_chain.h', f'// ({commit}): do not edit; run it again when they change.',
           '// The shader library ABI: the driver segment layout and the binding kinds nxnative\'s host and its shader build share,',
           '// and the version of the translation chain nxmac::dmsh is a port of (the host loads only libraries named after it).', '#pragma once', '', '#include <string_view>', '',
           'namespace nxmac::dmsh::abi {', '', f'inline constexpr std::string_view kChain = "{m.group(1)}";', ''] + rows + ['', '}  // namespace nxmac::dmsh::abi', '']
    with open(args.output, 'w', encoding='utf-8', newline='\n') as f: f.write('\n'.join(out))
    if args.clang_format:   # the repository's .clang-format: found from the header's folder up
        subprocess.run([args.clang_format, '-i', args.output], check=True)
    else:
        print('export_dmsh_abi: no clang-format: format the header before committing it (cmake --build --preset debug --target format)')
    print(f'{args.output}: {len(rows)} values, chain {m.group(1)}')


if __name__ == '__main__':
    main()
